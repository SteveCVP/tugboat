import { randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

function esc(value) {
  return String(value ?? "").replaceAll("\\", "\\\\").replaceAll("|", "\\|").replaceAll("\n", " ").trim();
}

function row(values) {
  return `| ${values.map(esc).join(" | ")} |`;
}

function evidenceText(refs) {
  return refs?.length ? refs.join(", ") : "pending";
}

function actorText(actor) {
  if (!actor) return "unknown";
  return `${actor.name}${actor.runtime ? ` (${actor.runtime})` : ""}`;
}

function writeAtomic(file, contents) {
  const temp = `${file}.tmp-${process.pid}-${randomUUID()}`;
  fs.writeFileSync(temp, contents, { mode: 0o600 });
  fs.renameSync(temp, file);
}

export function ledgerMarkdown(state) {
  const metadata = state.metadata;
  const requirements = Object.values(state.requirements);
  const preservations = Object.values(state.preservations);
  const slices = Object.values(state.slices);
  const amendments = Object.values(state.amendments);
  const promotions = state.promotions ?? [];
  return `# Tugboat Requirement Ledger

> Generated from \`events.jsonl\`. Do not edit this file directly.

## Mission Metadata

- Mission ID: \`${metadata.id}\`
- Mission title: \`${metadata.title}\`
- Owner: \`${metadata.owner}\`
- Repository: \`${metadata.repository}\`
- Worktree: \`${metadata.worktree}\`
- Branch: \`${metadata.branch}\`
- Baseline SHA: \`${metadata.baselineGitSha}\`
- Current SHA: \`${state.currentHead ?? metadata.baselineGitSha}\`
- Mission status: \`${state.status}\`
- Protocol version: \`${state.protocolVersion}\`
- State revision: \`${state.revision}\`
- Genesis event hash: \`${state.genesisEventHash}\`
- Source specification(s): \`${metadata.source.path}\`
- Source specification digest: \`${metadata.source.digest}\`
- Canonical deploy path: \`${metadata.deployPath}\`
- Critical path: \`${metadata.criticalPath.join(",")}\`

## Baseline And Preservation Contract

| ID | Preservation instruction | Source | Regression proof | Status |
|---|---|---|---|---|
${preservations.map((item) => row([item.id, item.instruction, item.source, evidenceText(item.evidenceRefs), item.status])).join("\n")}

## Requirement-To-Proof Ledger

| ID | Requirement | Source | Material | Acceptance | Proof target | Evidence | Result | Status |
|---|---|---|---|---|---|---|---|---|
${requirements.map((item) => row([item.id, item.requirement, item.source, item.material === false ? "no" : "yes", item.acceptance, item.proofTarget, evidenceText(item.evidenceRefs), item.result ?? "pending", item.status])).join("\n")}

## Release Slices

| Slice | Requirement IDs | Operator journey | Dependencies | Status |
|---|---|---|---|---|
${slices.map((slice) => row([slice.id, slice.requirementIds.join(","), slice.operatorJourney, slice.dependencies.join(",") || "none", slice.status])).join("\n")}

## Scope Amendments

| ID | Timestamp | Author | Affected IDs | Supersedes | Reason | Conflicts | Invalidated proof |
|---|---|---|---|---|---|---|---|
${amendments.map((item) => row([item.id, item.timestamp, actorText(item.actor), item.affectedIds.join(","), item.supersedes.join(",") || "none", item.reason, item.conflictsWith.join(",") || "none", Object.keys(item.invalidatedProof).join(",") || "none"])).join("\n")}

## Bundle Promotions

| Bundle | Timestamp | Author | Source requirements | Target requirements | Components | Reusable evidence | Expired evidence |
|---|---|---|---|---|---|---|---|
${promotions.map((item) => row([item.bundleId, item.timestamp, actorText(item.actor), item.sourceRequirementIds.join(","), item.targetRequirementIds.join(","), item.components.map((component) => component.targetPath).join(",") || "none", item.reusableEvidence.map((evidence) => evidence.sourceEvidenceId).join(",") || "none", item.expiredEvidence.map((evidence) => evidence.sourceEvidenceId).join(",") || "none"])).join("\n")}

## Completion Map

| Requirement ID | User-visible result | Evidence IDs | Status |
|---|---|---|---|
${requirements.filter((item) => item.status.startsWith("PROVEN(")).map((item) => row([item.id, item.result, item.evidenceRefs.join(","), item.status])).join("\n")}
`;
}

export function auditMarkdown(state) {
  return `# Tugboat Audit Log

> Generated from the append-only event log.

| Seq | Timestamp | Actor | Type | IDs | Reason |
|---|---|---|---|---|---|
${state.audit.map((entry) => row([entry.sequence, entry.timestamp, actorText(entry.actor), entry.type, entry.ids.join(",") || "none", entry.reason])).join("\n")}
`;
}

export function handoffMarkdown(state) {
  const active = state.status === "COMPLETE" ? [] : (() => {
    const slice = state.slices[state.activeSliceId];
    if (!slice) return [];
    const dependencies = [...new Set((slice.dependencies ?? []).flatMap((id) => state.slices[id]?.requirementIds ?? []))]
      .filter((id) => ["PENDING", "IN_PROGRESS", "BLOCKED"].includes(state.requirements[id]?.status));
    const candidates = dependencies.length ? dependencies : slice.requirementIds;
    return [...new Set(candidates)].filter((id) => ["PENDING", "IN_PROGRESS", "BLOCKED"].includes(state.requirements[id]?.status));
  })();
  const claims = Object.values(state.claims ?? {})
    .filter((claim) => claim.status === "ACTIVE")
    .sort((left, right) => left.id.localeCompare(right.id))
    .map((claim) => `${claim.id}:${claim.holder}:${claim.requirementIds.join(",")}:expires=${claim.expiresAt}`);
  return `# Tugboat Context Handoff

> Generated from canonical state.

- Updated: \`${state.handoff.updatedAt}\`
- Mission: \`${state.metadata.id}\`
- Mission status: \`${state.status}\`
- State revision: \`${state.revision}\`
- Branch / recorded SHA: \`${state.metadata.branch} / ${state.handoff.recordedGitSha}\`
- Active slice: \`${state.activeSliceId ?? "none"}\`
- Active requirement IDs: \`${active.join(",") || "none"}\`
- Active work claims: \`${claims.join("; ") || "none"}\`
- Current blocker/decision: \`${state.handoff.blocker ?? "none"}\`
- Exact next action: \`${state.handoff.nextAction}\`
- Next acceptance check: \`${state.handoff.nextCheck}\`
`;
}

export function completionMarkdown(state) {
  const proven = Object.values(state.requirements).filter((item) => item.status.startsWith("PROVEN("));
  return `# Tugboat Completion Report

Status: \`${state.status}\`

${state.status === "COMPLETE" ? `## Requirement Proof

| ID | Result | Evidence | Status |
|---|---|---|---|
${proven.map((item) => row([item.id, item.result, item.evidenceRefs.join(","), item.status])).join("\n")}` : "Populate only after the completion gate passes."}
`;
}

export function renderMission(dir, state) {
  const files = {
    "requirement-ledger.md": ledgerMarkdown(state),
    "audit-log.md": auditMarkdown(state),
    "context-handoff.md": handoffMarkdown(state),
    "completion-report.md": completionMarkdown(state),
  };
  for (const [name, contents] of Object.entries(files)) writeAtomic(path.join(dir, name), contents);
  return files;
}
